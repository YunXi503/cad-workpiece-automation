"""Generate source for a new CATIA VSTA test project from a synthetic CAD plan."""
import argparse
import base64
import json
from pathlib import Path
import re

HOST_ENTRY = r"""namespace HOST_GENERATED_NAMESPACE
{
    public sealed partial class ThisApplication : ObjectModelAgentLib.CATIAEntryPoint
    {
        public static void CATMain()
        {
            VerifyPortfolio("editor-catmain");
        }

        public void MacroPortfolioVerify()
        {
            VerifyPortfolio("catia-macro-list");
        }

        private static void VerifyPortfolio(string entry)
        {
            string folder = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "CodexPortfolioVstaQA");
            string output = Path.Combine(folder, entry + "-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(output);
            string log = Path.Combine(output, "runtime.txt");
            string plan = Path.Combine(output, "cad-plan.json");
            string sketches = Path.Combine(output, "sketches.json");
            string surfaces = Path.Combine(output, "surfaces.json");
            byte[] planBytes = Convert.FromBase64String("SYNTHETIC_CAD_PLAN_BASE64");
            File.WriteAllLines(log, new[]
            {
                "entry=" + entry,
                "process=" + Process.GetCurrentProcess().ProcessName,
                "apartment=" + Thread.CurrentThread.GetApartmentState()
            });
            try
            {
                using (SHA256 sha = SHA256.Create())
                    File.AppendAllText(log, "plan-sha256=" + BitConverter.ToString(sha.ComputeHash(planBytes)).Replace("-", "").ToLowerInvariant() + Environment.NewLine);
                File.WriteAllBytes(plan, planBytes);
                INFITF.Application app = CATIA;
                CadPortfolio.Vsta.MacroWorkflow.CreateSketches(app, plan, sketches);
                int count = CadPortfolio.Vsta.MacroWorkflow.CreateSurfaces(app, plan, sketches, surfaces);
                File.AppendAllText(log, "surfaces=" + count + Environment.NewLine + "status=verified" + Environment.NewLine);
            }
            catch (Exception error)
            {
                File.AppendAllText(log, "status=failed" + Environment.NewLine + error + Environment.NewLine);
                throw;
            }
        }
    }
}"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("host_namespace", help="Namespace from the blank VSTA ThisApplication.cs")
    parser.add_argument("plan", type=Path, help="cad-plan.json from the synthetic normal example")
    parser.add_argument("output", type=Path, help="New C# file to paste into the VSTA editor")
    args = parser.parse_args()
    if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*(\.[A-Za-z_][A-Za-z_0-9]*)*", args.host_namespace):
        parser.error("copy the namespace from the VSTA-generated ThisApplication.cs")
    try:
        plan_bytes = args.plan.read_bytes()
        plan = json.loads(plan_bytes)
        if not isinstance(plan, dict) or plan.get("schema") != "portfolio-cad/1" or plan.get("units") != "mm" or not plan.get("sides"):
            parser.error("use the CAD plan generated by the synthetic normal example")
        workflow = Path(__file__).with_name("MacroWorkflow.cs").read_text(encoding="utf-8-sig")
        host = HOST_ENTRY.replace("HOST_GENERATED_NAMESPACE", args.host_namespace).replace(
            "SYNTHETIC_CAD_PLAN_BASE64", base64.b64encode(plan_bytes).decode("ascii")
        )
        source = "using System.Diagnostics;\nusing System.Threading;\n" + workflow.rstrip() + "\n\n" + host + "\n"
        with args.output.open("x", encoding="utf-8-sig", newline="\r\n") as output:
            output.write(source)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    print(args.output.resolve())


if __name__ == "__main__":
    main()
